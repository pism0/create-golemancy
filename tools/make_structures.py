"""Writes the structure templates used by GameTests (and, later, Ponder scenes) as structure NBT.

There is no display in the build environment, so structures are generated by this script instead
of being saved from the in-game structure block. Re-run after editing:

    .venv/Scripts/python tools/make_structures.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))

import nbt  # noqa: E402

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), ".."))
DATA_VERSION = 3955  # Minecraft 1.21.1


def structure(size, blocks):
    """blocks: list of (x, y, z, block_name[, properties dict[, block entity nbt dict]])."""
    palette = []
    index = {}
    out_blocks = []
    for entry in blocks:
        x, y, z, name = entry[:4]
        props = entry[4] if len(entry) > 4 and entry[4] else {}
        be = entry[5] if len(entry) > 5 else None
        key = (name, tuple(sorted(props.items())))
        if key not in index:
            index[key] = len(palette)
            state = {"Name": name}
            if props:
                state["Properties"] = {k: str(v) for k, v in sorted(props.items())}
            palette.append(state)
        block = {"pos": [x, y, z], "state": index[key]}
        if be:
            block["nbt"] = be
        out_blocks.append(block)
    return {
        "size": [size[0], size[1], size[2]],
        "palette": palette,
        "blocks": out_blocks,
        "entities": [],
        "DataVersion": DATA_VERSION,
    }


def platform(width, height, depth, floor="minecraft:smooth_stone"):
    return structure((width, height, depth),
                     [(x, 0, z, floor) for x in range(width) for z in range(depth)])


def gametest_structures():
    base = os.path.join(ROOT, "src", "main", "resources", "data", "golemancy", "structure", "gametest")
    # A stone floor with open space above it. Golems stand on y = 1 (relative).
    nbt.write(os.path.join(base, "platform.nbt"), platform(9, 6, 9))
    # A larger arena for combat tests.
    nbt.write(os.path.join(base, "arena.nbt"), platform(15, 7, 15))
    return 2


if __name__ == "__main__":
    count = gametest_structures()
    try:
        import make_ponder  # noqa: F401  (added in Milestone 3)
        count += make_ponder.write_all()
    except ModuleNotFoundError:
        pass
    print(f"wrote {count} structure templates")
