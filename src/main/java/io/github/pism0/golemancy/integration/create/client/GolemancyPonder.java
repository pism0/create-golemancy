/**
 * Ponder scenes (SDD 8.5): one for the Binding Altar and one for the frame assembly line.
 *
 * <p>The schematics ({@code assets/golemancy/ponder/*.nbt}) are generated by
 * {@code tools/make_ponder.py} because the build machine cannot run the client to save them with
 * a structure block. Positions used here must match that script.
 */
public final class GolemancyPonder implements PonderPlugin {
    private GolemancyPonder() {
    }

    public static void register() {
        PonderIndex.addPlugin(new GolemancyPonder());
    }

    /**
     * Exports every scene title and caption into the lang file during datagen. Ponder only shows
     * translation keys at runtime, so without this the scenes display raw keys. Client setup does
     * not run during datagen, hence the plugin is registered here as well (as Create does).
     */
    public static void provideLang(java.util.function.BiConsumer<String, String> consumer) {
        PonderIndex.addPlugin(new GolemancyPonder());
        PonderIndex.getLangAccess().provideLang(Golemancy.MOD_ID, consumer);
    }

    @Override
    public String getModId() {
        return Golemancy.MOD_ID;
    }

    @Override
    public void registerScenes(PonderSceneRegistrationHelper<ResourceLocation> helper) {
        helper.forComponents(ModBlocks.BINDING_ALTAR.getId())
                .addStoryBoard("binding_altar", GolemancyPonder::bindingAltar);

        List<ResourceLocation> lineComponents = new ArrayList<>();
        for (String material : ModItems.MATERIALS) {
            lineComponents.add(ModItems.part(material, "torso_shell").getId());
            for (String frame : ModItems.FRAMES) {
                lineComponents.add(ModItems.frame(material, frame).getId());
            }
        }
        helper.forComponents(lineComponents).addStoryBoard("frame_line", GolemancyPonder::frameLine);
    }

    // Schematic "binding_altar": 5x3x5, shaft at (2,1,2), altar at (2,2,2).
    private static void bindingAltar(SceneBuilder builder, SceneBuildingUtil util) {
        CreateSceneBuilder scene = new CreateSceneBuilder(builder);
        scene.title("binding_altar", "Binding golems at the Binding Altar");
        scene.configureBasePlate(0, 0, 5);
        scene.world().showSection(util.select().layer(0), Direction.UP);
        scene.idle(5);

        BlockPos altar = util.grid().at(2, 2, 2);
        Selection altarSelect = util.select().position(altar);
        Selection shaft = util.select().position(2, 1, 2);
        scene.world().setKineticSpeed(altarSelect, 0);
        scene.world().setKineticSpeed(shaft, 0);

        scene.world().showSection(shaft, Direction.DOWN);
        scene.idle(5);
        scene.world().showSection(altarSelect, Direction.DOWN);
        scene.idle(15);

        Vec3 top = util.vector().topOf(altar);
        scene.overlay().showText(70)
                .attachKeyFrame()
                .text("The Binding Altar joins a Construct Frame and a Core into a golem")
                .pointAt(top)
                .placeNearTarget();
        scene.idle(80);

        ItemStack frame = new ItemStack(ModItems.frame("stone", "guardian").get());
        ItemStack core = new ItemStack(ModItems.core("fire").get());
        scene.overlay().showControls(top, Pointing.DOWN, 30).withItem(frame);
        scene.idle(7);
        scene.world().modifyBlockEntity(altar, BindingAltarBlockEntity.class,
                be -> be.setForDisplay(frame, ItemStack.EMPTY, ItemStack.EMPTY, ItemStack.EMPTY));
        scene.idle(30);
        scene.overlay().showControls(top, Pointing.DOWN, 30).withItem(core);
        scene.idle(7);
        scene.world().modifyBlockEntity(altar, BindingAltarBlockEntity.class,
                be -> be.setForDisplay(frame, core, ItemStack.EMPTY, ItemStack.EMPTY));
        scene.idle(30);

        scene.overlay().showText(70)
                .attachKeyFrame()
                .text("Place them by hand, or feed them in with funnels, chutes, deployers or mechanical arms")
                .pointAt(top)
                .placeNearTarget();
        scene.idle(80);

        scene.overlay().showText(70)
                .colored(PonderPalette.BLUE)
                .text("A spell scroll can be added to inscribe one spell that matches the core's school")
                .pointAt(top)
                .placeNearTarget();
        scene.idle(80);

        scene.overlay().showText(60)
                .attachKeyFrame()
                .colored(PonderPalette.GREEN)
                .text("The altar is powered by a shaft from below")
                .pointAt(util.vector().centerOf(2, 1, 2))
                .placeNearTarget();
        scene.idle(20);
        scene.world().setKineticSpeed(shaft, 32);
        scene.world().setKineticSpeed(altarSelect, 32);
        scene.world().modifyBlock(altar, state -> state.setValue(BindingAltarBlock.WORKING, true), false);
        scene.effects().indicateSuccess(altar);
        scene.idle(70);

        ItemStack golem = GolemLifecycle.dormantStack(
                GolemSpec.create(Golemancy.id("guardian"), Golemancy.id("stone"), Golemancy.id("fire")), ConstructState.FRESH);
        scene.world().modifyBlock(altar, state -> state.setValue(BindingAltarBlock.WORKING, false), false);
        scene.world().modifyBlockEntity(altar, BindingAltarBlockEntity.class,
                be -> be.setForDisplay(ItemStack.EMPTY, ItemStack.EMPTY, ItemStack.EMPTY, golem));
        scene.overlay().showText(80)
                .attachKeyFrame()
                .text("The result is a Dormant Golem. Take it by hand or extract it with a funnel, then use it on the ground to deploy")
                .pointAt(top)
                .placeNearTarget();
        scene.idle(90);

        scene.overlay().showText(80)
                .colored(PonderPalette.RED)
                .text("Construct Remains can be rebuilt here with repair material and fuel instead of a new frame")
                .pointAt(top)
                .placeNearTarget();
        scene.idle(90);
        scene.markAsFinished();
    }

    // Schematic "frame_line": 5x4x5, depot at (2,1,2), deployer at (2,3,2), shaft at (2,3,3), cog at (2,3,4).
    private static void frameLine(SceneBuilder builder, SceneBuildingUtil util) {
        CreateSceneBuilder scene = new CreateSceneBuilder(builder);
        scene.title("frame_line", "Assembling Construct Frames");
        scene.configureBasePlate(0, 0, 5);
        scene.world().showSection(util.select().layer(0), Direction.UP);
        scene.idle(5);

        BlockPos depot = util.grid().at(2, 1, 2);
        BlockPos deployer = util.grid().at(2, 3, 2);
        Selection deployerSelect = util.select().position(deployer);
        Selection drive = util.select().fromTo(2, 3, 3, 2, 3, 4);
        scene.world().setKineticSpeed(deployerSelect, 0);
        scene.world().setKineticSpeed(drive, 0);

        scene.world().showSection(util.select().position(depot), Direction.DOWN);
        scene.idle(10);
        scene.world().showSection(deployerSelect, Direction.DOWN);
        scene.world().showSection(drive, Direction.DOWN);
        scene.idle(10);
        scene.world().setKineticSpeed(deployerSelect, -32);
        scene.world().setKineticSpeed(drive, 32);
        scene.idle(10);

        ItemStack shell = new ItemStack(ModItems.part("stone", "torso_shell").get());
        ItemStack incomplete = new ItemStack(ModItems.INCOMPLETE_FRAMES.get("stone_guardian").get());
        ItemStack done = new ItemStack(ModItems.frame("stone", "guardian").get());
        Vec3 depotTop = util.vector().topOf(depot);

        scene.overlay().showText(70)
                .attachKeyFrame()
                .text("Construct Frames are built by Sequenced Assembly, starting from a Torso Shell")
                .pointAt(depotTop)
                .placeNearTarget();
        scene.world().createItemOnBeltLike(depot, Direction.NORTH, shell);
        scene.idle(80);

        ItemStack[] deployed = {
                new ItemStack(ModItems.part("stone", "limb").get()),
                new ItemStack(ModItems.part("stone", "limb").get()),
                new ItemStack(ModItems.part("stone", "head").get()),
        };
        String[] captions = {
                "Deployers attach two limbs...",
                null,
                "...then the head",
        };
        for (int i = 0; i < deployed.length; i++) {
            ItemStack held = deployed[i];
            scene.world().modifyBlockEntityNBT(deployerSelect, DeployerBlockEntity.class,
                    nbt -> nbt.put("HeldItem", held.saveOptional(scene.world().getHolderLookupProvider())));
            if (captions[i] != null) {
                scene.overlay().showText(50)
                        .attachKeyFrame()
                        .text(captions[i])
                        .pointAt(util.vector().blockSurface(deployer, Direction.WEST))
                        .placeNearTarget();
            }
            scene.idle(10);
            scene.world().moveDeployer(deployer, 1, 25);
            scene.idle(25);
            scene.world().modifyBlockEntityNBT(deployerSelect, DeployerBlockEntity.class,
                    nbt -> nbt.put("HeldItem", ItemStack.EMPTY.saveOptional(scene.world().getHolderLookupProvider())));
            scene.world().removeItemsFromBelt(depot);
            scene.world().createItemOnBeltLike(depot, Direction.UP, incomplete);
            scene.world().moveDeployer(deployer, -1, 25);
            scene.idle(30);
        }

        scene.overlay().showText(70)
                .attachKeyFrame()
                .colored(PonderPalette.BLUE)
                .text("A Mechanical Press fixes the joints, and a last Deployer adds the Core Housing socket")
                .pointAt(depotTop)
                .placeNearTarget();
        scene.idle(80);

        scene.world().removeItemsFromBelt(depot);
        scene.world().createItemOnBeltLike(depot, Direction.UP, done);
        scene.overlay().showControls(depotTop, Pointing.DOWN, 50).withItem(done);
        scene.overlay().showText(80)
                .attachKeyFrame()
                .colored(PonderPalette.GREEN)
                .text("The finished frame goes to a Binding Altar. Each material and frame type has its own sequence, shown in JEI")
                .pointAt(depotTop)
                .placeNearTarget();
        scene.idle(90);
        scene.markAsFinished();
    }
}
